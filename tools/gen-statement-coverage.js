#!/usr/bin/env node
/* The statement coverage matrix (docs/specs/statement-coverage-spec.md):
 * taxonomy/statement-formats.json is the one source. This writes its table into
 * docs/specs/statement-capture-spec.md between the coverage markers and prints,
 * to stdout, the statement_shapes seed SQL for supported rows no seed migration
 * carries yet. It never writes a migration (SC6): a person numbers and applies it.
 *
 *   node tools/gen-statement-coverage.js            # rewrite the spec block, print SQL
 *   node tools/gen-statement-coverage.js --check    # exit 1 when the block is stale
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'taxonomy', 'statement-formats.json');
const SPEC = path.join(ROOT, 'docs', 'specs', 'statement-capture-spec.md');
const BEGIN = '<!-- coverage:begin -->', END = '<!-- coverage:end -->';

function load() { return JSON.parse(fs.readFileSync(JSON_PATH, 'utf8')); }

/* the seeded (sender, shape) pairs, from every migration that inserts into statement_shapes */
function seededShapes() {
  const dir = path.join(ROOT, 'supabase', 'migrations');
  const out = new Set();
  for (const f of fs.readdirSync(dir).sort()) {
    if (!f.endsWith('.sql')) continue;
    const src = fs.readFileSync(path.join(dir, f), 'utf8');
    if (!/insert into public\.statement_shapes/.test(src)) continue;
    for (const m of src.matchAll(/\(\s*'([^']+)',\s*'([^']+)',\s*(true|false)/g)) out.add(m[1] + '|' + m[2]);
  }
  return out;
}

function table(data) {
  const rows = data.formats.slice().sort((a, b) => (a.provider + a.product).localeCompare(b.provider + b.product));
  const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|');
  let h = '| provider | sender | product | file | locked | status | fixture | seen | note |\n|---|---|---|---|---|---|---|---|---|\n';
  for (const r of rows) {
    h += '| ' + [r.provider, esc(r.sender), r.product, r.ext, r.locked ? 'yes' : 'no', '**' + r.status + '**',
      r.fixture ? '`' + r.fixture + '`' : '', r.seen || '', esc(r.note || '')].join(' | ') + ' |\n';
  }
  return '*(generated by `tools/gen-statement-coverage.js` from `taxonomy/statement-formats.json` v' + data.version + ', ' + data.updated + '; do not edit by hand)*\n\n' + h;
}

function render(data) {
  const spec = fs.readFileSync(SPEC, 'utf8');
  const a = spec.indexOf(BEGIN), b = spec.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('coverage markers missing in ' + SPEC);
  const block = BEGIN + '\n' + table(data) + END;
  return { spec, next: spec.slice(0, a) + block + spec.slice(b + END.length) };
}

function seedSql(data) {
  const have = seededShapes();
  const missing = data.formats.filter((r) => r.status === 'supported' && !have.has(r.sender + '|' + r.subject_shape));
  if (!missing.length) return '';
  return '-- statement_shapes seed for supported formats not yet seeded (write as a NEW numbered migration):\n' +
    'insert into public.statement_shapes (sender_address, shape, is_statement, source) values\n' +
    missing.map((r) => "  ('" + r.sender + "', '" + r.subject_shape.replace(/'/g, "''") + "', true, 'seed')").join(',\n') +
    '\non conflict (sender_address, shape) do nothing;\n';
}

if (require.main === module) {
  const data = load();
  const { spec, next } = render(data);
  if (process.argv.includes('--check')) {
    if (spec !== next) { console.error('statement-capture-spec.md §15 coverage block is stale: run node tools/gen-statement-coverage.js'); process.exit(1); }
    console.log('coverage block is current'); process.exit(0);
  }
  fs.writeFileSync(SPEC, next);
  console.log('wrote the coverage block into ' + path.relative(ROOT, SPEC) + ' (' + data.formats.length + ' formats)');
  const sql = seedSql(data);
  if (sql) console.log('\n' + sql); else console.log('every supported format is seeded');
}
module.exports = { load, table, render, seedSql, seededShapes };
